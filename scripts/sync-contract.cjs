#!/usr/bin/env node
const fs = require("node:fs");
const path = require("node:path");
const assert = require("node:assert/strict");
const { convertIdlToCamelCase } = require("@coral-xyz/anchor/dist/cjs/idl.js");

const projectRoot = path.resolve(__dirname, "..");
const generated = "src/generated/hash-timestamp";

function files(directory, prefix = "") {
  if (!fs.existsSync(directory)) return [];
  return fs
    .readdirSync(directory, { withFileTypes: true })
    .flatMap((entry) => {
      if (entry.isSymbolicLink())
        throw new Error(`Refusing SDK symlink: ${entry.name}`);
      const relative = path.join(prefix, entry.name);
      return entry.isDirectory()
        ? files(path.join(directory, entry.name), relative)
        : [relative];
    })
    .sort();
}

function context(root) {
  const contract = path.join(root, "hash-timestamp");
  const source = path.join(contract, "app/sdk");
  if (!fs.existsSync(path.join(source, "hashTimestamp.ts"))) {
    throw new Error(
      "Initialize the SDK source: git submodule update --init --recursive",
    );
  }
  const dependencies = JSON.parse(
    fs.readFileSync(path.join(root, "package.json")),
  ).dependencies;
  const expected = JSON.parse(
    fs.readFileSync(path.join(contract, "package.json")),
  ).dependencies;
  assert.equal(
    dependencies["@coral-xyz/anchor"],
    expected["@coral-xyz/anchor"],
    "Anchor must match the SDK version",
  );
  return {
    contract,
    source,
    destination: path.join(root, generated),
    normalize: require(path.join(contract, "scripts/check-idl.cjs")).normalize,
  };
}

function write(file, contents) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, contents);
}

/** A narrow compatibility guard for web3.js 1.98's optional RPC rentEpoch. */
function sdkContents(name, contents) {
  if (name !== path.join("protocol", "hashes.ts")) return contents;
  const source = contents.toString("utf8");
  const marker = "  const rentEpoch = Buffer.alloc(8);";
  assert(
    source.includes(marker),
    "Upstream account hashing changed; review the rentEpoch compatibility guard",
  );
  return Buffer.from(
    source.replace(
      marker,
      "  // Browser integration: modern RPC types allow rentEpoch to be absent.\n" +
        '  if (info.rentEpoch === undefined) throw new Error("RPC snapshot is missing rentEpoch");\n' +
        marker,
    ),
  );
}

function validatedIdl(ctx, input) {
  const baseline = JSON.parse(
    fs.readFileSync(path.join(ctx.contract, "tests/fixtures/idl.json")),
  );
  const idl = input ? JSON.parse(fs.readFileSync(input)) : baseline;
  assert.deepEqual(
    ctx.normalize(idl),
    ctx.normalize(baseline),
    "IDL differs from the reviewed contract baseline",
  );
  const manifest = fs.readFileSync(
    path.join(ctx.contract, "programs/hash-timestamp/Cargo.toml"),
    "utf8",
  );
  assert.equal(
    idl.metadata.version,
    manifest.match(/^version\s*=\s*"([^"]+)"/m)?.[1],
    "IDL version differs from the contract",
  );
  const config = fs.readFileSync(
    path.join(ctx.contract, "Anchor.toml"),
    "utf8",
  );
  const addresses = [
    ...config.matchAll(/^hash_timestamp\s*=\s*"([^"]+)"/gm),
  ].map((m) => m[1]);
  assert(
    addresses.length > 0 &&
      addresses.every((address) => address === idl.address),
    "IDL program address differs from Anchor.toml",
  );
  return idl;
}

function typeSource(idl) {
  const json = JSON.stringify(convertIdlToCamelCase(idl), null, 2);
  return `// Generated by scripts/sync-contract.cjs using Anchor's IDL converter. Do not edit.\nexport type HashTimestamp = ${json};\nexport const IDL: HashTimestamp = ${json};\n`;
}

function syncSdk(root) {
  const ctx = context(root);
  const sourceFiles = files(ctx.source);
  assert(
    sourceFiles.length && sourceFiles.every((name) => name.endsWith(".ts")),
    "Unexpected SDK file type; review before exporting",
  );
  const output = path.join(ctx.destination, "app/sdk");
  files(output); // Reject existing destination symlinks before writing.
  for (const name of sourceFiles)
    write(
      path.join(output, name),
      sdkContents(name, fs.readFileSync(path.join(ctx.source, name))),
    );
  // This directory contains only managed SDK copies, never application source.
  for (const name of files(output))
    if (!sourceFiles.includes(name)) fs.unlinkSync(path.join(output, name));
  return sourceFiles.length;
}

function syncIdl(root, input) {
  const ctx = context(root);
  const idl = validatedIdl(ctx, input);
  write(
    path.join(ctx.destination, "idl.json"),
    `${JSON.stringify(idl, null, 2)}\n`,
  );
  write(
    path.join(ctx.destination, "target/types/hash_timestamp.ts"),
    typeSource(idl),
  );
}

function check(root) {
  const ctx = context(root);
  const output = path.join(ctx.destination, "app/sdk");
  assert.deepEqual(
    files(output),
    files(ctx.source),
    "SDK file list is stale; run npm run sync:sdk",
  );
  for (const name of files(ctx.source)) {
    assert(
      fs
        .readFileSync(path.join(output, name))
        .equals(
          sdkContents(name, fs.readFileSync(path.join(ctx.source, name))),
        ),
      `SDK drift in ${name}; run npm run sync:sdk`,
    );
  }
  const idl = validatedIdl(ctx, path.join(ctx.destination, "idl.json"));
  assert.equal(
    fs.readFileSync(
      path.join(ctx.destination, "target/types/hash_timestamp.ts"),
      "utf8",
    ),
    typeSource(idl),
    "IDL types are stale; run npm run sync:idl",
  );
}

function main(args) {
  const [command, flag, input, ...rest] = args;
  if (
    !["sdk", "idl", "all", "check"].includes(command) ||
    rest.length ||
    (flag && (flag !== "--idl" || !input || !["idl", "all"].includes(command)))
  ) {
    throw new Error(
      "Usage: node scripts/sync-contract.cjs sdk|idl|all|check [--idl path/to/idl.json]",
    );
  }
  // Validate an explicit IDL before any managed source is overwritten.
  if (input) validatedIdl(context(projectRoot), path.resolve(input));
  if (command === "sdk" || command === "all")
    console.log(
      `Synced ${syncSdk(projectRoot)} SDK files with the documented rentEpoch compatibility guard.`,
    );
  if (command === "idl" || command === "all") {
    syncIdl(projectRoot, input && path.resolve(input));
    console.log("Synced reviewed IDL and Anchor-compatible types.");
  }
  if (command === "check") {
    check(projectRoot);
    console.log("SDK, IDL, types and program identity match the submodule.");
  }
}

module.exports = { syncSdk, syncIdl, check, typeSource };
if (require.main === module) {
  try {
    main(process.argv.slice(2));
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
